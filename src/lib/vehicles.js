function resolveImage(source, width = 1200) {
  if (source.startsWith("https://")) return source;
  return photo(source, width);
}

export const vehicles = vehicleRecords.map((record) => {
  const leadImage = vehicleImageOverrides[record.slug] || record.image;
  const references = galleryImagesByType[record.type] || [
    carPhoto,
    redCar,
    roadCar,
  ];
  const gallery = [
    leadImage,
    ...references.filter((image) => image !== leadImage),
  ].slice(0, 4);

  return {
    ...record,
    image: resolveImage(leadImage),
    gallery: gallery.map((image, index) =>
      resolveImage(image, index === 0 ? 1800 : 1400),
    ),
  };
});

export function getVehicle(slug) {
  return vehicles.find((item) => item.slug === slug);
}

export function formatPrice(value, currency = "USD") {
  return new Intl.NumberFormat(currency === "PKR" ? "en-PK" : "en-US", {
    style: "currency",
    currency,
    maximumFractionDigits: 0,
  }).format(value);
}
